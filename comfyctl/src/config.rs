//! `config` — Parseo tipado de variables de entorno y lectura efímera de `/run/comfyui-pass` (§6.2, §9).

use crate::sys;
use std::collections::BTreeMap;
use std::env;
use std::path::{Path, PathBuf};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ModelProfile {
    All,
    General,
    Realistic,
    Anime,
    Minimal,
    Studio,
}

impl ModelProfile {
    pub fn from_str_lossy(raw: &str) -> (Self, bool) {
        match raw.trim() {
            "all" | "" => (Self::All, true),
            "general" => (Self::General, true),
            "realistic" => (Self::Realistic, true),
            "anime" => (Self::Anime, true),
            "minimal" => (Self::Minimal, true),
            "studio" => (Self::Studio, true),
            _ => (Self::All, false),
        }
    }

    pub const fn as_str(self) -> &'static str {
        match self {
            Self::All => "all",
            Self::General => "general",
            Self::Realistic => "realistic",
            Self::Anime => "anime",
            Self::Minimal => "minimal",
            Self::Studio => "studio",
        }
    }

    pub const fn default_min_disk_gb(self, skip_download: bool) -> u64 {
        if skip_download {
            return 5;
        }
        match self {
            Self::Studio => 180,
            Self::All => 75,
            Self::General | Self::Realistic | Self::Anime => 45,
            Self::Minimal => 10,
        }
    }
}

#[derive(Debug, Clone)]
#[allow(clippy::struct_excessive_bools)]
pub struct RuntimeConfig {
    pub model_profile: ModelProfile,
    pub model_profile_raw: String,
    pub model_profile_valid: bool,
    pub skip_model_download: bool,
    pub comfy_user: String,
    pub comfy_pass: Option<String>,
    pub comfy_pass_autogenerated: bool,
    pub hf_token: Option<String>,
    pub studio_llm_key: Option<String>,
    pub studio_llm_base_url: String,
    pub studio_llm_model: String,
    pub studio_llm_fallback_base_url: String,
    pub studio_llm_fallback_model: String,
    pub studio_comfyui_url: String,
    pub studio_data_dir: PathBuf,
    pub studio_server_port: u16,
    pub studio_python_bin: Option<PathBuf>,
    pub studio_server_script: Option<PathBuf>,
    pub studio_include_animate: bool,
    pub comfy_app_dir: PathBuf,
    pub comfy_data_dir: PathBuf,
    pub comfy_extra_args: String,
    pub comfy_max_restarts: u32,
    pub comfy_restart_delay_s: u64,
    pub comfy_healthy_uptime_s: u64,
    pub log_max_mb: u64,
    pub enable_web_terminal: bool,
    pub hf_hub_disable_xet: Option<String>,
    pub strict_start: bool,
    pub strict_require_gpu: bool,
    pub strict_min_vram_mb: u64,
    pub strict_warn_vram_mb: u64,
    pub strict_min_driver: u32,
    pub strict_min_ram_mb: u64,
    pub strict_warn_ram_mb: u64,
    pub strict_min_disk_gb: u64,
    pub strict_fatal_grace_s: u64,
    pub status_server_port: u16,
    pub supervisor_json_path: PathBuf,
    pub strict_json_path: PathBuf,
    pub started_at_path: PathBuf,
    pub image_json_path: PathBuf,
    pub htpasswd_path: PathBuf,
    pub require_htpasswd: bool,
    pub nvidia_smi_bin: PathBuf,
    pub vast_containerlabel: String,
    pub vast_tcp_port_8188: String,
}

impl RuntimeConfig {
    /// Carga la configuración para subcomandos CLI (`strict-check`, `report`, `diag`, `serve`).
    /// Lee `/run/comfyui-pass` sin borrarlo (`R-11`) y no exige `.htpasswd` si aún no corrió `start.sh` (`R-02`).
    pub fn from_env() -> Self {
        let mut map = BTreeMap::new();
        for (k, v) in env::vars() {
            map.insert(k, v);
        }
        let pass_file = Path::new("/run/comfyui-pass");
        let file_pass = sys::read_secret_file(pass_file, false);
        let mut cfg = Self::from_map(&map, file_pass);
        if !matches!(
            map.get("STRICT_REQUIRE_HTPASSWD").map(String::as_str),
            Some("1" | "true")
        ) {
            cfg.require_htpasswd = false;
        }
        cfg
    }

    /// Carga la configuración para el demonio residente (`comfyctl supervise`),
    /// leyendo y borrando inmediatamente `/run/comfyui-pass` (`unlink`, §9 / `R-11`)
    /// y exigiendo `/etc/nginx/.htpasswd` válido (`R-02`).
    pub fn from_env_supervise() -> Self {
        let mut map = BTreeMap::new();
        for (k, v) in env::vars() {
            map.insert(k, v);
        }
        let pass_file = Path::new("/run/comfyui-pass");
        let file_pass = sys::read_and_unlink_secret(pass_file);
        let mut cfg = Self::from_map(&map, file_pass);
        cfg.require_htpasswd = true;
        cfg
    }

    #[allow(clippy::too_many_lines)]
    pub fn from_map(vars: &BTreeMap<String, String>, secret_file_pass: Option<String>) -> Self {
        let get = |k: &str| -> Option<&str> { vars.get(k).map(String::as_str) };
        let get_u64 = |k: &str, default: u64| -> u64 {
            get(k)
                .and_then(|s| s.trim().parse::<u64>().ok())
                .unwrap_or(default)
        };
        let get_u32 = |k: &str, default: u32| -> u32 {
            get(k)
                .and_then(|s| s.trim().parse::<u32>().ok())
                .unwrap_or(default)
        };

        let raw_profile = get("MODEL_PROFILE").unwrap_or("all").to_string();
        let (model_profile, model_profile_valid) = ModelProfile::from_str_lossy(&raw_profile);
        let skip_model_download = get("SKIP_MODEL_DOWNLOAD").unwrap_or("0") == "1";

        let comfy_extra_args = get("COMFYUI_EXTRA_ARGS").unwrap_or("").to_string();
        let cpu_flag_present = comfy_extra_args
            .split_whitespace()
            .any(|tok| tok == "--cpu");

        let default_req_gpu = !cpu_flag_present;
        let strict_require_gpu = match get("STRICT_REQUIRE_GPU") {
            Some("1" | "true") => true,
            Some("0" | "false") => false,
            _ => default_req_gpu,
        };

        let strict_start = !matches!(get("STRICT_START"), Some("0" | "false"));
        let default_disk = model_profile.default_min_disk_gb(skip_model_download);
        let strict_min_disk_gb = get_u64("STRICT_MIN_DISK_GB", default_disk);

        let comfy_pass = secret_file_pass.or_else(|| {
            get("COMFY_PASS")
                .map(str::trim)
                .filter(|s| !s.is_empty())
                .map(ToString::to_string)
        });
        let hf_token = get("HF_TOKEN")
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .map(ToString::to_string);
        let studio_llm_key = get("STUDIO_LLM_KEY")
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .map(ToString::to_string);

        let data_dir_raw = get("COMFY_DATA_DIR").unwrap_or("/workspace/comfyui-data");
        let comfy_data_dir = PathBuf::from(data_dir_raw);
        let studio_data_dir = get("STUDIO_DATA_DIR")
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .map_or_else(|| comfy_data_dir.join("studio"), PathBuf::from);
        let studio_server_port = get("STUDIO_SERVER_PORT")
            .and_then(|s| s.trim().parse::<u16>().ok())
            .unwrap_or(18190);
        let studio_python_bin = get("STUDIO_PYTHON_BIN")
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .map(PathBuf::from);
        let studio_server_script = get("STUDIO_SERVER_SCRIPT")
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .map(PathBuf::from);
        let studio_include_animate = get("STUDIO_INCLUDE_ANIMATE").unwrap_or("0") == "1";

        let status_server_port = get("STATUS_SERVER_PORT")
            .and_then(|s| s.trim().parse::<u16>().ok())
            .unwrap_or(18189);

        let require_htpasswd = !matches!(get("STRICT_REQUIRE_HTPASSWD"), Some("0" | "false"));

        Self {
            model_profile,
            model_profile_raw: if raw_profile.is_empty() {
                "all".to_string()
            } else {
                raw_profile
            },
            model_profile_valid,
            skip_model_download,
            comfy_user: get("COMFY_USER").unwrap_or("admin").to_string(),
            comfy_pass,
            comfy_pass_autogenerated: get("COMFY_PASS_AUTOGENERATED").unwrap_or("0") == "1",
            hf_token,
            studio_llm_key,
            studio_llm_base_url: get("STUDIO_LLM_BASE_URL")
                .map(str::trim)
                .filter(|s| !s.is_empty())
                .unwrap_or("https://dashscope-intl.aliyuncs.com/compatible-mode/v1")
                .to_string(),
            studio_llm_model: get("STUDIO_LLM_MODEL")
                .map(str::trim)
                .filter(|s| !s.is_empty())
                .unwrap_or("qwen3-vl-plus")
                .to_string(),
            studio_llm_fallback_base_url: get("STUDIO_LLM_FALLBACK_BASE_URL")
                .map(str::trim)
                .filter(|s| !s.is_empty())
                .unwrap_or("https://api.deepseek.com")
                .to_string(),
            studio_llm_fallback_model: get("STUDIO_LLM_FALLBACK_MODEL")
                .map(str::trim)
                .filter(|s| !s.is_empty())
                .unwrap_or("deepseek-chat")
                .to_string(),
            studio_comfyui_url: get("STUDIO_COMFYUI_URL")
                .map(str::trim)
                .filter(|s| !s.is_empty())
                .unwrap_or("http://127.0.0.1:18188")
                .to_string(),
            studio_data_dir,
            studio_server_port,
            studio_python_bin,
            studio_server_script,
            studio_include_animate,
            comfy_app_dir: PathBuf::from(get("COMFY_APP_DIR").unwrap_or("/opt/ComfyUI")),
            comfy_data_dir,
            comfy_extra_args,
            comfy_max_restarts: get_u32("COMFY_MAX_RESTARTS", 5),
            comfy_restart_delay_s: get_u64("COMFY_RESTART_DELAY", 5),
            comfy_healthy_uptime_s: get_u64("COMFY_HEALTHY_UPTIME", 600),
            log_max_mb: get_u64("LOG_MAX_MB", 200),
            enable_web_terminal: get("ENABLE_WEB_TERMINAL").unwrap_or("0") == "1",
            hf_hub_disable_xet: get("HF_HUB_DISABLE_XET").map(ToString::to_string),
            strict_start,
            strict_require_gpu,
            strict_min_vram_mb: get_u64("STRICT_MIN_VRAM_MB", 20000),
            strict_warn_vram_mb: get_u64("STRICT_WARN_VRAM_MB", 22000),
            strict_min_driver: get_u32("STRICT_MIN_DRIVER", 570),
            strict_min_ram_mb: get_u64("STRICT_MIN_RAM_MB", 16384),
            strict_warn_ram_mb: get_u64("STRICT_WARN_RAM_MB", 32768),
            strict_min_disk_gb,
            strict_fatal_grace_s: get_u64("STRICT_FATAL_GRACE", 600),
            status_server_port,
            supervisor_json_path: PathBuf::from(
                get("COMFY_SUPERVISOR_JSON").unwrap_or("/run/comfyui-supervisor.json"),
            ),
            strict_json_path: PathBuf::from(
                get("COMFY_STRICT_JSON").unwrap_or("/run/comfyui-strict.json"),
            ),
            started_at_path: PathBuf::from(
                get("COMFY_STARTED_AT_FILE").unwrap_or("/run/comfyui-started-at"),
            ),
            image_json_path: PathBuf::from(
                get("COMFY_IMAGE_JSON").unwrap_or("/etc/comfyui/image.json"),
            ),
            htpasswd_path: PathBuf::from(
                get("COMFY_HTPASSWD_PATH").unwrap_or("/etc/nginx/.htpasswd"),
            ),
            require_htpasswd,
            nvidia_smi_bin: PathBuf::from(get("COMFY_NVIDIA_SMI_BIN").unwrap_or("nvidia-smi")),
            vast_containerlabel: get("VAST_CONTAINERLABEL").unwrap_or("local").to_string(),
            vast_tcp_port_8188: get("VAST_TCP_PORT_8188").unwrap_or("8188").to_string(),
        }
    }

    pub fn masked_pass_status(&self) -> String {
        if self.comfy_pass_autogenerated {
            "<autogenerada — ver logs del contenedor>".to_string()
        } else if self.comfy_pass.is_some() {
            "<definida por el usuario>".to_string()
        } else {
            "<no definida>".to_string()
        }
    }

    pub fn masked_hf_status(&self) -> String {
        if self.hf_token.is_some() {
            "<definido>".to_string()
        } else {
            "<no definido>".to_string()
        }
    }

    pub fn masked_studio_llm_key_status(&self) -> String {
        if self.studio_llm_key.is_some() {
            "<definida>".to_string()
        } else {
            "<no definida>".to_string()
        }
    }
}
