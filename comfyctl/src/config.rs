//! `config` — Parseo tipado de variables de entorno y lectura efímera de `/run/comfyui-pass` (§6.2, §9).

use crate::sys;
use std::collections::BTreeMap;
use std::env;
use std::path::{Path, PathBuf};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ModelProfile {
    All,
    General,
    Realistic,
    Anime,
    Minimal,
}

impl ModelProfile {
    pub fn from_str_lossy(raw: &str) -> (Self, bool) {
        match raw.trim() {
            "all" | "" => (Self::All, true),
            "general" => (Self::General, true),
            "realistic" => (Self::Realistic, true),
            "anime" => (Self::Anime, true),
            "minimal" => (Self::Minimal, true),
            _ => (Self::All, false),
        }
    }

    pub const fn as_str(self) -> &'static str {
        match self {
            Self::All => "all",
            Self::General => "general",
            Self::Realistic => "realistic",
            Self::Anime => "anime",
            Self::Minimal => "minimal",
        }
    }

    pub const fn default_min_disk_gb(self, skip_download: bool) -> u64 {
        if skip_download {
            return 5;
        }
        match self {
            Self::All => 80,
            Self::General | Self::Realistic | Self::Anime => 45,
            Self::Minimal => 15,
        }
    }
}

#[derive(Debug, Clone)]
#[allow(clippy::struct_excessive_bools)]
pub struct RuntimeConfig {
    pub model_profile: ModelProfile,
    pub model_profile_raw: String,
    pub model_profile_valid: bool,
    pub skip_model_download: bool,
    pub comfy_user: String,
    pub comfy_pass: Option<String>,
    pub comfy_pass_autogenerated: bool,
    pub hf_token: Option<String>,
    pub comfy_app_dir: PathBuf,
    pub comfy_data_dir: PathBuf,
    pub comfy_extra_args: String,
    pub comfy_max_restarts: u32,
    pub comfy_restart_delay_s: u64,
    pub comfy_healthy_uptime_s: u64,
    pub log_max_mb: u64,
    pub enable_web_terminal: bool,
    pub hf_hub_disable_xet: Option<String>,
    pub strict_start: bool,
    pub strict_require_gpu: bool,
    pub strict_min_vram_mb: u64,
    pub strict_min_driver: u32,
    pub strict_min_ram_mb: u64,
    pub strict_min_disk_gb: u64,
    pub strict_fatal_grace_s: u64,
    pub status_server_port: u16,
    pub supervisor_json_path: PathBuf,
    pub strict_json_path: PathBuf,
    pub started_at_path: PathBuf,
}

impl RuntimeConfig {
    pub fn from_env() -> Self {
        let mut map = BTreeMap::new();
        for (k, v) in env::vars() {
            map.insert(k, v);
        }
        let pass_file = Path::new("/run/comfyui-pass");
        let file_pass = sys::read_and_unlink_secret(pass_file);
        Self::from_map(&map, file_pass)
    }

    pub fn from_map(vars: &BTreeMap<String, String>, secret_file_pass: Option<String>) -> Self {
        let get = |k: &str| -> Option<&str> { vars.get(k).map(String::as_str) };
        let get_u64 = |k: &str, default: u64| -> u64 {
            get(k)
                .and_then(|s| s.trim().parse::<u64>().ok())
                .unwrap_or(default)
        };
        let get_u32 = |k: &str, default: u32| -> u32 {
            get(k)
                .and_then(|s| s.trim().parse::<u32>().ok())
                .unwrap_or(default)
        };

        let raw_profile = get("MODEL_PROFILE").unwrap_or("all").to_string();
        let (model_profile, model_profile_valid) = ModelProfile::from_str_lossy(&raw_profile);
        let skip_model_download = get("SKIP_MODEL_DOWNLOAD").unwrap_or("0") == "1";

        let comfy_extra_args = get("COMFYUI_EXTRA_ARGS").unwrap_or("").to_string();
        let cpu_flag_present = comfy_extra_args
            .split_whitespace()
            .any(|tok| tok == "--cpu");

        let default_req_gpu = !cpu_flag_present;
        let strict_require_gpu = match get("STRICT_REQUIRE_GPU") {
            Some("1" | "true") => true,
            Some("0" | "false") => false,
            _ => default_req_gpu,
        };

        let strict_start = !matches!(get("STRICT_START"), Some("0" | "false"));
        let default_disk = model_profile.default_min_disk_gb(skip_model_download);
        let strict_min_disk_gb = get_u64("STRICT_MIN_DISK_GB", default_disk);

        let comfy_pass = secret_file_pass.or_else(|| {
            get("COMFY_PASS")
                .map(str::trim)
                .filter(|s| !s.is_empty())
                .map(ToString::to_string)
        });
        let hf_token = get("HF_TOKEN")
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .map(ToString::to_string);

        let status_server_port = get("STATUS_SERVER_PORT")
            .and_then(|s| s.trim().parse::<u16>().ok())
            .unwrap_or(18189);

        Self {
            model_profile,
            model_profile_raw: if raw_profile.is_empty() {
                "all".to_string()
            } else {
                raw_profile
            },
            model_profile_valid,
            skip_model_download,
            comfy_user: get("COMFY_USER").unwrap_or("admin").to_string(),
            comfy_pass,
            comfy_pass_autogenerated: get("COMFY_PASS_AUTOGENERATED").unwrap_or("0") == "1",
            hf_token,
            comfy_app_dir: PathBuf::from(get("COMFY_APP_DIR").unwrap_or("/opt/ComfyUI")),
            comfy_data_dir: PathBuf::from(
                get("COMFY_DATA_DIR").unwrap_or("/workspace/comfyui-data"),
            ),
            comfy_extra_args,
            comfy_max_restarts: get_u32("COMFY_MAX_RESTARTS", 5),
            comfy_restart_delay_s: get_u64("COMFY_RESTART_DELAY", 5),
            comfy_healthy_uptime_s: get_u64("COMFY_HEALTHY_UPTIME", 600),
            log_max_mb: get_u64("LOG_MAX_MB", 200),
            enable_web_terminal: get("ENABLE_WEB_TERMINAL").unwrap_or("0") == "1",
            hf_hub_disable_xet: get("HF_HUB_DISABLE_XET").map(ToString::to_string),
            strict_start,
            strict_require_gpu,
            strict_min_vram_mb: get_u64("STRICT_MIN_VRAM_MB", 16000),
            strict_min_driver: get_u32("STRICT_MIN_DRIVER", 570),
            strict_min_ram_mb: get_u64("STRICT_MIN_RAM_MB", 16384),
            strict_min_disk_gb,
            strict_fatal_grace_s: get_u64("STRICT_FATAL_GRACE", 600),
            status_server_port,
            supervisor_json_path: PathBuf::from(
                get("COMFY_SUPERVISOR_JSON").unwrap_or("/run/comfyui-supervisor.json"),
            ),
            strict_json_path: PathBuf::from(
                get("COMFY_STRICT_JSON").unwrap_or("/run/comfyui-strict.json"),
            ),
            started_at_path: PathBuf::from(
                get("COMFY_STARTED_AT_FILE").unwrap_or("/run/comfyui-started-at"),
            ),
        }
    }
}
